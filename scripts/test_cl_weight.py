def marks(path: str, text: str) -> str:
    """One letter per line: C comment, T test, - other."""
    a = cw.analyze(path, text)
    return "".join("C" if n in a.comment else "T" if n in a.test else "-"
                   for n in range(1, text.count("\n") + 2))


class ParseDiffTest(unittest.TestCase):
    def test_parses_hunks_renames_and_deletions(self):
        text = "\n".join([
            "diff --git a/m.py b/m.py",
            "--- a/m.py",
            "+++ b/m.py",
            "@@ -3,2 +3 @@",
            "--- not a header",
            "-old",
            "+new",
            "diff --git a/old.txt b/new.txt",
            "similarity index 100%",
            "rename from old.txt",
            "rename to new.txt",
            "diff --git a/gone.c b/gone.c",
            "deleted file mode 100644",
            "--- a/gone.c",
            "+++ /dev/null",
            "@@ -1 +0,0 @@",
            "-int x;",
            'diff --git "a/caf\\303\\251\\t.py" "b/caf\\303\\251\\t.py"',
            "new file mode 100644",
            "diff --git a/a b/c d b/a b/c d",
            "old mode 100644",
            "new mode 100755",
        ])
        modified, renamed, deleted, quoted, spaced = cw.parse_diff(text)
        self.assertEqual(modified.deleted, [(3, "-- not a header"), (4, "old")])
        self.assertEqual(modified.added, [(3, "new")])
        self.assertEqual((renamed.old_path, renamed.new_path), ("old.txt", "new.txt"))
        self.assertEqual((deleted.old_path, deleted.new_path), ("gone.c", None))
        self.assertEqual((quoted.old_path, quoted.new_path), (None, "caf\u00e9\t.py"))
        self.assertEqual(spaced.path, "a b/c d")


class ClassifyTest(unittest.TestCase):
    def test_builtin_rules_and_overrides(self):
        cases = {
            "Cargo.lock": "generated",
            "api/x.go": "generated",  # by header marker below
            "pkg/tests/data.json": "test",
            "src/app.test.ts": "test",
            "CMakeLists.txt": "config",
            "docs/guide.md": "doc",
            "src/main.rs": "code",
        }
        for path, expected in cases.items():
            head = "// Code generated by protoc. DO NOT EDIT." if path == "api/x.go" else ""
            self.assertEqual(cw.classify(path, head, {}), expected, path)
        overrides = {"generated": ["vendor/*"], "doc": ["vendor/*"]}
        self.assertEqual(cw.classify("vendor/a/b.c", "", overrides), "generated")


class WeighTest(unittest.TestCase):
    def test_weights_by_line_kind(self):
        diff = cw.FileDiff("a.rs", "a.rs", added=[(1, "fn f() {}"), (2, ""), (3, "// c"),
                                                  (4, "#[test]")])
        new = cw.Analysis(comment={3}, test={4})
        self.assertEqual(cw.weigh(diff, "code", new=new).tenths, 10 + 0 + 3 + 5)

    def test_deleted_file_counts_one_line(self):
        diff = cw.FileDiff("a.py", None, deleted=[(1, "x = 1"), (2, "y = 2")])
        self.assertEqual(cw.weigh(diff, "code").tenths, 10)


class AnalyzeTest(unittest.TestCase):
    def test_python_docstrings_and_hashes_in_strings(self):
        text = ('"""Doc.\n"""\nx = """not\ndoc"""\ns = "# no"\n    # yes\n'
                'f(\n    "a"\n)\nx = \\\n    "b"')
        self.assertEqual(marks("m.py", text), "CC---C-----")

    def test_c_family_strings_and_block_comments(self):
        self.assertEqual(marks("a.ts", 'a("//");\n/* x\n y */\n/* z */ b();'), "-CC-")
        self.assertEqual(marks("a.ts", "t = `${ `//` }\n// q`;"), "--")
        self.assertEqual(marks("a.go", "s := `/*\n*/`\n// c"), "--C")
        self.assertEqual(marks("a.cc", 'R"d(\n// )d";\nint n = 1\'0;\n// c'), "---C")

    def test_rust_nested_comments_and_test_module(self):
        text = ("/* a /* b */\nc */\nfn f<'a>() -> char { '}' }\n"
                "#[cfg(test)]\nmod tests {\n    fn t() { r#\"}\"#; }\n}\nfn g() {}")
        self.assertEqual(marks("lib.rs", text), "CC-TTTT-")


class EndToEndTest(unittest.TestCase):
    def setUp(self):
        self.dir = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.dir)
        (self.dir / "jj.toml").write_text('user.name = "T"\nuser.email = "t@example.com"\n')
        self.env = {**os.environ, "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1",
                    "JJ_CONFIG": str(self.dir / "jj.toml")}
        self.repo = self.dir / "repo"
        self.repo.mkdir()

    def sh(self, *cmd):
        subprocess.run(cmd, cwd=self.repo, env=self.env, check=True, capture_output=True)

    def weigh(self, *args):
        proc = subprocess.run([sys.executable, str(SCRIPT), "--json", *args], cwd=self.repo,
                              env=self.env, capture_output=True, text=True)
        return proc.returncode, json.loads(proc.stdout) if proc.stdout else None

    def test_git_staged_change_and_limit(self):
        self.sh("git", "init", "-q")
        (self.repo / "big.py").write_text("x = 1\n" * 301)
        self.sh("git", "add", "big.py")
        code, report = self.weigh()
        self.assertEqual((code, report["vcs"], report["total"]), (1, "git", 301.0))
        self.assertEqual(self.weigh("--allow-large", "vendoring")[0], 0)
        (self.repo / ".azote-cl.toml").write_text("limit = 1000\n")
        self.assertEqual(self.weigh()[0], 2)

    @unittest.skipUnless(shutil.which("jj"), "jj is not installed")
    def test_jj_working_copy_change(self):
        self.sh("jj", "git", "init")
        (self.repo / "a.py").write_text("# c\nx = 1\n")
        (self.repo / "README.md").write_text("hi\n")
        (self.repo / ".azote-cl.toml").write_text('[paths]\ngenerated = ["README.md"]\n')
        code, report = self.weigh()
        self.assertEqual((code, report["vcs"], report["total"]), (0, "jj", 2.3))


if __name__ == "__main__":
    unittest.main()
